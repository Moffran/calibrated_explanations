"""Generate platform skill-discovery packages from one canonical skill catalogue.

Generic, dependency-free tool (with ``instruction_tooling.py``). Repository
settings live in the ``[tool.skill-packages]`` table of ``pyproject.toml``::

    [tool.skill-packages]
    source = "skills"                              # canonical <name>/SKILL.md catalogue
    targets = [".claude/skills", ".agents/skills"]

Contract
--------
* Every directory directly under ``source`` is a skill. Its name must follow the
  Agent Skills rule and match the ``name`` in its ``SKILL.md`` frontmatter.
* Each target receives a complete copy of every skill. UTF-8 text files are
  written with LF line endings; binary files are copied byte for byte.
* Paths must be portable relative paths. Unsafe names, case-insensitive
  collisions, overlapping source/target paths, symbolic links, junctions and
  special files are rejected, never followed.

Ownership
---------
A target skill directory is generated exactly when its ``SKILL.md`` carries the
generated notice that this tool inserts after the frontmatter. Generated
directories are owned entirely by the tool: they are rewritten when they differ
from the source and removed when their skill leaves the catalogue. Any other
entry in a target is never touched; if it has the name of a canonical skill,
synchronization is blocked until it is moved away.

All targets are planned before anything is written, and nothing is written if
any target is blocked. ``--check`` never writes and fails on pending changes.

Usage
-----
    python scripts/quality/sync_skill_packages.py --check
    python scripts/quality/sync_skill_packages.py --write
"""

from __future__ import annotations

import argparse
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11 (dev extras provide tomli)
    import tomli as tomllib  # type: ignore[no-redef]

try:  # repository root on sys.path (tests, ``python -m``)
    from scripts.quality import instruction_tooling as tooling
except ModuleNotFoundError:  # direct execution: scripts/quality is sys.path[0]
    import instruction_tooling as tooling  # type: ignore[no-redef]

ValidationError = tooling.ValidationError

GENERATOR = "scripts/quality/sync_skill_packages.py"
SKILL_FILE = "SKILL.md"
NOTICE_SUFFIX = f" by {GENERATOR}; do not edit. -->"
IGNORED_NAMES = frozenset({"__pycache__", ".DS_Store", "Thumbs.db"})

Package = dict[PurePosixPath, bytes]


@dataclass(frozen=True)
class Config:
    """Resolved synchronization settings."""

    root: Path
    source: PurePosixPath
    targets: tuple[PurePosixPath, ...]


@dataclass
class TargetPlan:
    """Pending changes for one target: generated directories to remove or rewrite."""

    target: PurePosixPath
    removes: list[str] = field(default_factory=list)
    writes: dict[str, Package] = field(default_factory=dict)


@dataclass
class Report:
    """Outcome of one reconciliation pass."""

    blockers: list[str] = field(default_factory=list)
    pending: list[str] = field(default_factory=list)
    changes: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Configuration and source discovery
# ---------------------------------------------------------------------------


def load_config(root: Path, pyproject: Path | None = None) -> Config:
    """Read and validate ``[tool.skill-packages]`` from ``pyproject.toml``."""
    path = pyproject or root / "pyproject.toml"
    try:
        table = tomllib.loads(path.read_text(encoding="utf-8"))["tool"]["skill-packages"]
    except (OSError, KeyError, TypeError, tomllib.TOMLDecodeError) as exc:
        raise ValidationError(f"{path}: missing or invalid [tool.skill-packages] table") from exc
    context = "[tool.skill-packages]"
    source = tooling.validate_relative_path(table.get("source"), context=f"{context} source")
    raw_targets = table.get("targets")
    if not isinstance(raw_targets, list) or not raw_targets:
        raise ValidationError(f"{context} targets must be a non-empty list")
    targets = tuple(
        tooling.validate_relative_path(item, context=f"{context} targets") for item in raw_targets
    )
    configured = (source, *targets)
    for index, first in enumerate(configured):
        for second in configured[index + 1 :]:
            if tooling.paths_overlap(first, second):
                raise ValidationError(f"{context}: {first} and {second} overlap")
    return Config(root=root, source=source, targets=targets)


def _notice(source: PurePosixPath, skill: str) -> str:
    return f"<!-- Generated from {source}/{skill}/{SKILL_FILE}{NOTICE_SUFFIX}"


def _render(data: bytes, is_text: bool, relative: PurePosixPath, *, notice: str) -> bytes:
    """Return the generated bytes for one source file."""
    if not is_text:
        return data
    text = data.decode("utf-8").replace("\r\n", "\n")
    if relative != PurePosixPath(SKILL_FILE):
        return text.encode("utf-8")
    lines = text.split("\n")
    fences = [i for i, line in enumerate(lines) if line.strip().lstrip("﻿") == "---"]
    if len(fences) < 2 or fences[0] != 0:
        raise ValidationError(f"{notice}: missing YAML frontmatter")
    lines.insert(fences[1] + 1, notice)
    return "\n".join(lines).encode("utf-8")


def _read_package(directory: Path, *, label: str) -> Package:
    """Return ``{relative path: bytes}`` for every file in a skill directory."""
    files: Package = {}
    keys: set[str] = set()
    for item in tooling.scan_tree(directory, context=label, ignored_names=IGNORED_NAMES):
        if item.is_dir:
            continue
        relative = tooling.validate_relative_path(item.relative.as_posix(), context=label)
        if tooling.casefold_key(relative) in keys:
            raise ValidationError(f"{label}/{relative}: case-insensitive path collision")
        keys.add(tooling.casefold_key(relative))
        files[relative] = (directory / Path(*relative.parts)).read_bytes()
    return files


def discover_skills(config: Config) -> dict[str, Package]:
    """Return ``{skill: {relative path: generated bytes}}`` for the catalogue."""
    tooling.ensure_no_link_ancestors(config.root, config.source, context="source")
    source_root = config.root / Path(*config.source.parts)
    if not source_root.is_dir():
        raise ValidationError(f"canonical skill source {config.source} does not exist")
    skills: dict[str, Package] = {}
    seen_names: set[str] = set()
    for entry in sorted(source_root.iterdir(), key=lambda p: p.name):
        label = f"{config.source}/{entry.name}"
        if entry.name in IGNORED_NAMES:
            continue
        if tooling.is_link_like(entry):
            raise ValidationError(f"{label}: symbolic links and junctions are not allowed")
        if entry.is_file():
            continue  # catalogue-level files such as README.md are not skills
        if not entry.is_dir():
            raise ValidationError(f"{label}: unsupported filesystem object")
        tooling.validate_skill_name(entry.name, context=label)
        if entry.name.casefold() in seen_names:
            raise ValidationError(f"{label}: case-insensitive skill name collision")
        seen_names.add(entry.name.casefold())
        if not (entry / SKILL_FILE).is_file():
            raise ValidationError(f"{label}: missing {SKILL_FILE}")
        tooling.validate_skill_metadata(entry / SKILL_FILE, entry.name)

        notice = _notice(config.source, entry.name)
        rendered: Package = {}
        for relative, data in _read_package(entry, label=label).items():
            _, is_text = tooling.read_text_or_binary(entry / Path(*relative.parts))
            if relative == PurePosixPath(SKILL_FILE) and not is_text:
                raise ValidationError(f"{label}/{SKILL_FILE}: must be UTF-8 text")
            rendered[relative] = _render(data, is_text, relative, notice=notice)
        skills[entry.name] = rendered
    if not skills:
        raise ValidationError(f"no skills found under {config.source}")
    return skills


# ---------------------------------------------------------------------------
# Planning and application
# ---------------------------------------------------------------------------


def is_generated(directory: Path) -> bool:
    """Return True when *directory* is a skill package written by this tool."""
    skill_md = directory / SKILL_FILE
    if tooling.is_link_like(directory) or tooling.is_link_like(skill_md):
        return False
    if not directory.is_dir() or not skill_md.is_file():
        return False
    try:
        text = skill_md.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return any(
        line.startswith("<!-- Generated from ") and line.endswith(NOTICE_SUFFIX)
        for line in text.splitlines()
    )


def _plan_target(config: Config, target: PurePosixPath, skills: dict[str, Package]) -> TargetPlan:
    plan = TargetPlan(target=target)
    tooling.ensure_no_link_ancestors(config.root, target, context="target")
    root = config.root / Path(*target.parts)
    if root.exists() and not root.is_dir():
        raise ValidationError(f"{target}: target exists and is not a directory")

    wanted = {name.casefold(): name for name in skills}
    existing = sorted(root.iterdir(), key=lambda p: p.name) if root.is_dir() else []
    present: set[str] = set()
    for entry in existing:
        key = entry.name.casefold()
        generated = is_generated(entry)
        if key in wanted:
            present.add(key)
            if not generated:
                raise ValidationError(
                    f"{target}/{entry.name}: not a generated package but named like canonical "
                    f"skill {wanted[key]}; move it away"
                )
            name = wanted[key]
            if (
                entry.name != name
                or _read_package(entry, label=f"{target}/{entry.name}") != skills[name]
            ):
                plan.removes.append(entry.name)
                plan.writes[name] = skills[name]
        elif generated:
            _read_package(entry, label=f"{target}/{entry.name}")  # reject links before removal
            plan.removes.append(entry.name)
    for key, name in wanted.items():
        if key not in present:
            plan.writes[name] = skills[name]
    return plan


def _apply(config: Config, plan: TargetPlan, report: Report) -> None:
    root = config.root / Path(*plan.target.parts)
    for name in plan.removes:
        shutil.rmtree(root / name)
        report.changes.append(f"removed {plan.target}/{name}")
    for name, files in sorted(plan.writes.items()):
        for relative, data in sorted(files.items(), key=lambda item: str(item[0])):
            destination = root / name / Path(*relative.parts)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
        report.changes.append(f"wrote {plan.target}/{name}")


def synchronize(config: Config, *, write: bool) -> Report:
    """Plan every target, then apply all plans only if none is blocked."""
    report = Report()
    try:
        skills = discover_skills(config)
        plans = [_plan_target(config, target, skills) for target in config.targets]
    except (ValidationError, OSError) as exc:
        report.blockers.append(str(exc))
        return report
    for plan in plans:
        removed = set(plan.removes) - set(plan.writes)
        report.pending.extend(f"{plan.target}/{name}: obsolete package" for name in sorted(removed))
        report.pending.extend(
            f"{plan.target}/{name}: missing or stale" for name in sorted(plan.writes)
        )
    if write:
        for plan in plans:
            _apply(config, plan, report)
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."), help="Repository root.")
    parser.add_argument("--config", type=Path, default=None, help="pyproject.toml to read.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Regenerate skill packages.")
    mode.add_argument("--check", action="store_true", help="Check without changing files.")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    try:
        config = load_config(root, args.config)
    except ValidationError as exc:
        print(f"Skill package synchronization failed: {exc}")
        return 1
    report = synchronize(config, write=args.write)

    for line in report.changes:
        print(line)
    if report.blockers:
        print("Skill package synchronization blocked; no target was modified:")
        for line in report.blockers:
            print(f"- {line}")
        return 1
    if args.check and report.pending:
        print("Skill package check failed:")
        for line in report.pending:
            print(f"- {line}")
        print("Run: make skills-sync")
        return 1
    targets = ", ".join(str(t) for t in config.targets)
    if args.write:
        print(f"Skill packages synchronized ({len(report.changes)} change(s)) for: {targets}")
    else:
        print(f"Skill package check passed for: {targets}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
