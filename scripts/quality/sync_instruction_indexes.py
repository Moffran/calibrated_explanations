"""Generate and validate instruction discovery indexes.

The generator reads normative metadata directly from ADR, engineering-standard,
and canonical skill sources. Generated indexes are discovery surfaces only.
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import quote

try:  # repository root on sys.path (tests, ``python -m``)
    from scripts.quality import instruction_tooling as tooling
except ModuleNotFoundError:  # direct execution: scripts/quality is sys.path[0]
    import instruction_tooling as tooling  # type: ignore[no-redef]

GENERATED_FILES = (
    "development/adrs/README.md",
    "development/standards/README.md",
    "skills/README.md",
    "docs/contributor/agent_skills.md",
)

_GENERATED_HEADER = (
    "<!-- Generated by scripts/quality/sync_instruction_indexes.py; do not edit. -->\n"
)
_ADR_ID_PATTERN = re.compile(r"ADR-\d{3}$")
_STANDARD_ID_PATTERN = re.compile(r"STD-\d{3}$")
_VALID_ADR_STATUSES = frozenset({"accepted", "proposed", "superseded", "withdrawn"})
_VALID_STANDARD_STATUSES = frozenset({"active", "accepted", "proposed", "superseded", "withdrawn"})


@dataclass(frozen=True)
class GovernanceRecord:
    """Machine-readable ADR or engineering-standard record."""

    identifier: str
    title: str
    status: str
    description: str
    superseded_by: tuple[str, ...]
    source: Path


@dataclass(frozen=True)
class SkillRecord:
    """Machine-readable canonical skill record."""

    name: str
    description: str
    source: Path


MetadataError = tooling.ValidationError
_parse_frontmatter = tooling.parse_frontmatter
_require_string = tooling.require_string
_ACTIVE_STATUSES = frozenset({"accepted", "active"})
_HISTORICAL_STATUSES = frozenset({"superseded", "withdrawn"})


def _require_references(path: Path, metadata: dict[str, Any], key: str) -> tuple[str, ...]:
    value = metadata.get(key)
    if not isinstance(value, list) or any(
        not isinstance(item, str) or not item.strip() for item in value
    ):
        raise MetadataError(f"{path.as_posix()}: {key} must be a JSON-style string list")
    references = tuple(item.strip() for item in value)
    if len(set(references)) != len(references):
        raise MetadataError(f"{path.as_posix()}: {key} lists a reference twice")
    return references


def _read_governance_record(path: Path, *, kind: str) -> GovernanceRecord:
    metadata = _parse_frontmatter(path)
    identifier = _require_string(path, metadata, "id")
    title = _require_string(path, metadata, "title")
    status = _require_string(path, metadata, "status").lower()
    description = _require_string(path, metadata, "description")
    if "supersedes" in metadata:
        raise MetadataError(
            f"{path.as_posix()}: supersedes is derived; declare superseded_by on the "
            "superseded record instead"
        )
    superseded_by = _require_references(path, metadata, "superseded_by")

    pattern = _ADR_ID_PATTERN if kind == "ADR" else _STANDARD_ID_PATTERN
    valid_statuses = _VALID_ADR_STATUSES if kind == "ADR" else _VALID_STANDARD_STATUSES
    if pattern.fullmatch(identifier) is None:
        raise MetadataError(f"{path.as_posix()}: invalid {kind} identifier {identifier!r}")
    if status not in valid_statuses:
        allowed = ", ".join(sorted(valid_statuses))
        raise MetadataError(
            f"{path.as_posix()}: invalid status {status!r}; expected one of {allowed}"
        )
    if kind == "ADR" and path.name.startswith("superseded ") != (status == "superseded"):
        raise MetadataError(f"{path.as_posix()}: superseded filename and metadata status disagree")
    if kind == "Standard" and not path.name.startswith(f"{identifier}-"):
        raise MetadataError(f"{path.as_posix()}: filename does not match identifier {identifier}")
    if kind == "ADR" and identifier not in path.name:
        raise MetadataError(f"{path.as_posix()}: filename does not match identifier {identifier}")
    return GovernanceRecord(
        identifier=identifier,
        title=title,
        status=status,
        description=description,
        superseded_by=superseded_by,
        source=path,
    )


def _read_skill_record(path: Path) -> SkillRecord:
    name, description = tooling.validate_skill_metadata(path, path.parent.name)
    return SkillRecord(name=name, description=description, source=path)


def _unique_records(records: list[GovernanceRecord], *, root: Path) -> dict[str, GovernanceRecord]:
    by_id: dict[str, GovernanceRecord] = {}
    for record in records:
        if record.identifier in by_id:
            first = by_id[record.identifier].source.relative_to(root).as_posix()
            second = record.source.relative_to(root).as_posix()
            raise MetadataError(
                f"duplicate record identifier {record.identifier}: {first} and {second}"
            )
        by_id[record.identifier] = record
    return by_id


def _discover_records(root: Path) -> tuple[list[GovernanceRecord], list[GovernanceRecord]]:
    adr_paths = [
        path
        for path in sorted((root / "development/adrs").glob("*.md"))
        if path.name != "README.md"
    ]
    standard_paths = sorted((root / "development/standards").glob("STD-*.md"))
    if not adr_paths:
        raise MetadataError("no canonical ADR source files found")
    if not standard_paths:
        raise MetadataError("no canonical engineering-standard source files found")
    adrs = [_read_governance_record(path, kind="ADR") for path in adr_paths]
    standards = [_read_governance_record(path, kind="Standard") for path in standard_paths]
    _unique_records(adrs + standards, root=root)
    return sorted(adrs, key=lambda record: record.identifier), sorted(
        standards, key=lambda record: record.identifier
    )


def _discover_skills(root: Path) -> list[SkillRecord]:
    skills_root = root / "skills"
    tooling.ensure_no_link_ancestors(
        root, tooling.validate_relative_path("skills", context="skills"), context="skills"
    )
    skill_dirs = sorted(
        path for path in skills_root.iterdir() if path.is_dir() or tooling.is_link_like(path)
    )
    if not skill_dirs:
        raise MetadataError("no canonical skill directories found")
    seen: dict[str, str] = {}
    for directory in skill_dirs:
        if tooling.is_link_like(directory):
            raise MetadataError(
                f"skills/{directory.name}: symbolic links and junctions are not allowed"
            )
        tooling.validate_skill_name(directory.name, context=f"skills/{directory.name}")
        if directory.name.casefold() in seen:
            raise MetadataError(
                f"skills/{directory.name}: collides case-insensitively with "
                f"skills/{seen[directory.name.casefold()]}"
            )
        seen[directory.name.casefold()] = directory.name
    missing = [directory.name for directory in skill_dirs if not (directory / "SKILL.md").is_file()]
    if missing:
        raise MetadataError("canonical skill directories missing SKILL.md: " + ", ".join(missing))
    return [_read_skill_record(directory / "SKILL.md") for directory in skill_dirs]


def _validate_supersession_references(records: list[GovernanceRecord], *, root: Path) -> None:
    """Validate ``superseded_by`` targets and status consistency.

    Supersession is stored once, on the superseded record; the reverse
    direction is derived. A record is ``superseded`` exactly when it has a
    ``superseded_by`` entry. A successor is either an accepted or active record
    or, for historical successors, an existing repository path.
    """
    by_id = {record.identifier: record for record in records}
    for record in records:
        label = record.source.relative_to(root).as_posix()
        for reference in record.superseded_by:
            if reference == record.identifier:
                raise MetadataError(f"{label}: record cannot supersede itself")
            successor = by_id.get(reference)
            if successor is not None:
                if successor.status not in _ACTIVE_STATUSES:
                    raise MetadataError(
                        f"{label}: successor {reference} must be accepted or active, "
                        f"not {successor.status!r}"
                    )
                continue
            tooling.validate_relative_path(reference, context=label)
            if not (root / reference).exists():
                raise MetadataError(f"{label}: invalid supersession reference {reference!r}")
        if (record.status == "superseded") != bool(record.superseded_by):
            raise MetadataError(
                f"{label}: status 'superseded' requires, and is required by, superseded_by"
            )


def _escape_table(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def _governance_index(
    records: list[GovernanceRecord],
    *,
    heading: str,
    source_note: str,
) -> str:
    active = [
        record for record in records if record.status not in {"proposed", "superseded", "withdrawn"}
    ]
    proposed = [record for record in records if record.status == "proposed"]
    historical = [record for record in records if record.status in {"superseded", "withdrawn"}]

    lines = [
        _GENERATED_HEADER.rstrip(),
        f"# {heading}",
        "",
        "This generated discovery index is not normative authority. Read the source file",
        "for the binding decision; use its status and description to decide applicability.",
        "",
        source_note,
        "",
        "## Active decisions",
        "",
        "| Identifier | Title | Applicability | Status | Source |",
        "|---|---|---|---|---|",
    ]
    for record in active:
        source = record.source.name
        source_link = quote(source)
        lines.append(
            f"| `{record.identifier}` | {_escape_table(record.title)} | "
            f"{_escape_table(record.description)} | `{record.status}` | "
            f"[{source}](./{source_link}) |"
        )
    if not active:
        lines.append("| — | None | No active records | — | — |")

    lines.extend(
        [
            "",
            "## Proposed decisions",
            "",
            "| Identifier | Title | Applicability | Status | Source |",
            "|---|---|---|---|---|",
            *(
                [
                    f"| `{record.identifier}` | {_escape_table(record.title)} | "
                    f"{_escape_table(record.description)} | `{record.status}` | "
                    f"[{record.source.name}](./{quote(record.source.name)}) |"
                    for record in proposed
                ]
                or ["| — | None | No proposed records | — | — |"]
            ),
        ]
    )

    lines.extend(
        [
            "",
            "## Historical decisions",
            "",
            "| Identifier | Title | Applicability | Status | Source |",
            "|---|---|---|---|---|",
            *(
                [
                    f"| `{record.identifier}` | {_escape_table(record.title)} | "
                    f"{_escape_table(record.description)} | `{record.status}` | "
                    f"[{record.source.name}](./{quote(record.source.name)}) |"
                    for record in historical
                ]
                or ["| — | None | No historical records | — | — |"]
            ),
            "",
        ]
    )
    return "\n".join(lines)


def _skill_index(records: list[SkillRecord], *, rtd: bool) -> str:
    heading = "Agent skill catalogue" if rtd else "Canonical CE skills"
    lines = [
        _GENERATED_HEADER.rstrip(),
        f"# {heading}",
        "",
        "This generated discovery index is derived from canonical `skills/*/SKILL.md`",
        "frontmatter. Select a skill for its workflow; the linked `SKILL.md` is the",
        "task-specific execution contract. Edit skills only under `skills/`; the",
        "platform discovery packages are generated from it by `make skills-sync`.",
        "",
        "| Skill | Description | Source |",
        "|---|---|---|",
    ]
    for record in records:
        if rtd:
            source = (
                "https://github.com/Moffran/calibrated_explanations/blob/main/"
                f"skills/{record.name}/SKILL.md"
            )
        else:
            source = f"./{record.name}/SKILL.md"
        lines.append(
            f"| `{record.name}` | {_escape_table(record.description)} | [SKILL.md]({source}) |"
        )
    lines.append("")
    return "\n".join(lines)


def build_generated_files(root: Path) -> dict[str, str]:
    """Build all generated indexes from canonical repository sources."""
    root = root.resolve()
    adrs, standards = _discover_records(root)
    skills = _discover_skills(root)
    _validate_supersession_references([*adrs, *standards], root=root)
    return {
        "development/adrs/README.md": _governance_index(
            adrs,
            heading="Architecture decision record index",
            source_note=(
                "Canonical ADR sources: `development/adrs/ADR-*.md` and historical "
                "`superseded ADR-*.md` files."
            ),
        ),
        "development/standards/README.md": _governance_index(
            standards,
            heading="Engineering standard index",
            source_note="Canonical standard sources: `development/standards/STD-*.md`.",
        ),
        "skills/README.md": _skill_index(skills, rtd=False),
        "docs/contributor/agent_skills.md": _skill_index(skills, rtd=True),
    }


def synchronize(root: Path, *, write: bool) -> int:
    """Validate metadata and either write or check generated indexes."""
    root = root.resolve()
    try:
        generated = build_generated_files(root)
    except (MetadataError, OSError) as exc:
        print(f"Instruction index validation failed: {exc}")
        return 1

    if write:
        for relative_path, content in generated.items():
            destination = root / relative_path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {len(generated)} instruction indexes.")
        return 0

    stale: list[str] = []
    for relative_path, expected in generated.items():
        destination = root / relative_path
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            stale.append(relative_path)
    if stale:
        print("Instruction index check failed; stale or missing generated files:")
        for relative_path in stale:
            print(f"- {relative_path}")
        print("Run: python scripts/quality/sync_instruction_indexes.py --write")
        return 1
    print("Instruction index check passed.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root",
        default=".",
        type=Path,
        help="Repository root (defaults to the current directory).",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Regenerate derived indexes.")
    mode.add_argument("--check", action="store_true", help="Check indexes without changing files.")
    args = parser.parse_args(argv)
    return synchronize(args.root, write=args.write)


if __name__ == "__main__":
    raise SystemExit(main())
